// Recursively widen every literal string leaf to `string` so other locales
// (e.g. ar.ts) can supply their own translated text without each value
// having to match the English literal type produced by `as const`.
type DeepStringify<T> = T extends string
  ? string
  : T extends object
    ? { [K in keyof T]: DeepStringify<T[K]> }
    : T;

export type TranslationDict = DeepStringify<typeof en>;
